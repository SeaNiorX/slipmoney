def get_translation_dict(lang="th"):
    """
    Returns a translation dictionary with English fallback.
    """
    if lang not in TRANSLATIONS:
        lang = "th"
    
    # Merge with English as fallback
    merged = dict(TRANSLATIONS["en"])
    merged.update(TRANSLATIONS.get(lang, {}))
    return merged
